# ['영화', '쇼핑']
# ['파이썬', '주식', '영화']

def 문제3():
    인스타_좋아요 = [15, 320, 87, 1500, 43, 980, 2100]

    좋아요=[ i for i in 인스타_좋아요 if i>=100]
    print(좋아요)
    # list comprehension 으로
    # 좋아요 100개 이상인 것만 필터해서 출력

문제3()
# [320, 1500, 980, 2100]

