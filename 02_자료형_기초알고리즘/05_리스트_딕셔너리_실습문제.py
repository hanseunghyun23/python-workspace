def 문제2():
    네이버_검색어 = ["파이썬", "날씨", "주식", "맛집", "영화", "쇼핑"]
    # 처음 3개만 출력
    print(네이버_검색어[:3])
    # 마지막 2개만 출력
    print(네이버_검색어[4:])

# 2칸씩 건너뛰어 출력
    print(네이버_검색어[::2])

 ##문제2()
