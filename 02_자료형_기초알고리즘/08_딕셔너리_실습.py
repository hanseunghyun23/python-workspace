def CSV파일읽기():
    데이터 = [
        {"이름": "철수", "점수": 85, "과목": "수학"},
        {"이름": "영희", "점수": 92, "과목": "영어"},
        {"이름": "민수", "점수": 78, "과목": "과학"},
        {"이름": "지수", "점수": 88, "과목": "국어"},
    ]

    for 행 in 데이터:
        print(f"이름: {행['이름']}, 점수: {행['점수'] }")

    # 이름: 철수, 점수: 85
    # 이름: 영희, 점수: 92
    # 이름: 민수, 점수: 78
    # 이름: 지수, 점수: 88

