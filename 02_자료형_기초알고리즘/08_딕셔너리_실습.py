def 상품딕셔너리만들기():
    상품 = ["아메리카노", "라떼", "녹차"]
    가격 = [2000, 3000, 2500]

    결과 = dict(zip(상품 ,가격 ))
    print(결과)

    # {"아메리카노": 2000, "라떼": 3000, "녹차": 2500}

