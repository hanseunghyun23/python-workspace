def 사이트주소딕셔너리만들기():
    사이트 = ["네이버", "구글", "다음"]
    주소 = ["www.naver.com", "www.google.com", "www.daum.net"]

    결과 = {사이트 : "https://" + 주소 for 사이트 ,주소  in zip(사이트 ,주소 )}
    print(결과)

    # {"네이버": "https://www.naver.com", "구글": "https://www.google.com", "다음": "https://www.daum.net"}

