def 학생점수출력():
    이름 = ["철수", "영희", "민수"]
    점수 = [85, 92, 78]

    for 이름   ,  점수    in zip( 이름  ,점수     ):
        print(f"{이름}  : {점수} 점")

    # 철수 : 85점
    # 영희 : 92점
    # 민수 : 78점

