def 골넣은선수출력():
    선수 = ["손흥민", "이강인", "황희찬", "김민재"]
    골수 = [2, 0, 1, 0]

    for  선수    , 골수 in zip(  선수   ,  골수   ):
        if  골수 >0    :
            print(f" {선수}  : {골수}골")

    # 손흥민 : 2골
    # 황희찬 : 1골

